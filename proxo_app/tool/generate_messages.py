"""Generate the local Dart catalog; no runtime translation or network dependency."""
from pathlib import Path
import json,re
root=Path(__file__).resolve().parents[1]
rows={}
for n,line in enumerate((root/'l10n/messages.tsv').read_text().splitlines(),1):
    if not line or line.startswith('#'):continue
    parts=line.split('\t')
    if len(parts)!=3 or any(not v.strip() for v in parts):raise ValueError(f'Invalid row {n}')
    key,ar,bd=parts
    if key in rows:raise ValueError(f'Duplicate row {n}: {key}')
    placeholders=lambda x:set(re.findall(r'\{\w+\}',x))
    if placeholders(key)!=placeholders(ar) or placeholders(key)!=placeholders(bd):raise ValueError(f'Placeholder mismatch {n}')
    rows[key]=(ar,bd)
def literal(text):return json.dumps(text,ensure_ascii=False).replace('$','\\$')
text='// Generated by tool/generate_messages.py from l10n/messages.tsv.\nconst proxoMessages = <String, (String, String)>{\n'
text+=''.join(f'  {literal(k)}: ({literal(ar)}, {literal(bd)}),\n' for k,(ar,bd) in rows.items())+'};\n'
(root/'lib/l10n/proxo_messages.dart').write_text(text)
print(f'{len(rows)} messages; both languages complete for registered keys.')
